//! The guide that lets any LLM customise Valerie. Generated from the running code so it never drifts, and written
//! into the config folder as AGENTS.md (read by Codex/OpenCode) plus CLAUDE.md (read by Claude Code).
use crate::command::{CATALOG, WITH_ARGS};
use crate::config::{config_dir, config_path, data_dir};
use std::fmt::Write;

const MARKER: &str = "<!-- generated by Valerie: edits here are overwritten; put notes in NOTES.md -->";

pub fn guide() -> String {
    let exe = std::env::current_exe().map(|p| p.display().to_string()).unwrap_or_else(|_| "valerie".into());
    let mut g = String::new();
    let _ = write!(
        g,
        r#"{MARKER}
# Customising Valerie (guide for AI assistants)

You are in the config folder of **Valerie**, the user's web browser. The user will ask you to change how their
browser looks or behaves ("make ⌘G open Gmail", "hide the URL bar", "add a button that saves this page to Notion").
Everything is plain files in this folder and Valerie reloads them the moment you save. No restart, no build.

## Files

| Path | What it is |
|---|---|
| `{config}` | The user's settings. Holds **only the options they changed**; everything else comes from the defaults. |
| `reference/default-config.yaml` | Every option with its default and a comment (read-only reference, regenerated each launch). |
| `plugins/<name>/plugin.yaml` | A plugin: commands, shortcuts, page scripts/styles, hooks. See `plugins/_example/`. |
| `plugins/<name>/style.css`, `script.js` | Applied to the sites listed in that plugin's `matches`. |
| `boosts/<host>.css`, `boosts/<host>.js` | Quick per-site CSS/JS without a plugin (e.g. `boosts/github.com.css`). |
| `NOTES.md` | Your own notes for next time (this file, AGENTS.md, is regenerated). |

Valerie's binary: `{exe}`

## How to make a change

1. Decide the smallest change: a setting in `config.yaml`, a boost, or a plugin.
2. Edit the file(s). In `config.yaml` add only the keys you change: maps (like `keybindings`, `sidebar`) merge key by
   key, lists (like `spaces`, `routes`) replace the default list entirely, and `null` removes a default entry.
3. Validate: run `"{exe}" check-config`. It parses the config and every plugin and prints exact errors. Fix and rerun
   until it says OK.
4. Tell the user what changed and which setting turns it back off.

House rules from the owner:
- When asked to add or remove something, do it **and** make it a setting so it can be switched back.
- Keep `config.yaml` readable: group related keys, add a short comment for anything non-obvious.
- Never add "press Esc to …" style messages.

## Common recipes

- **Add a site to Tab-to-search** (type its name in the command bar, press Tab, search it): add one entry under
  `site_search` in `config.yaml`, e.g. `Notion: {{ keywords: [notion], url: "https://www.notion.so/search?q=%s" }}`.
  `%s` is where the search goes. Remove a built-in one with `Reddit: null`.
- **Add a shortcut**: an entry under `keybindings`, e.g. `"CmdOrCtrl+Shift+G": {{ cmd: new_tab, url: "https://github.com" }}`.
- **Send a site to a space**: an entry in `routes` (this list replaces the default list, so copy the existing routes).
- **Restyle a site**: a CSS file in `boosts/<host>.css`.
- **Anything with logic** (several steps, page scripts, local programs): a plugin in `plugins/<name>/`.

## Settings

All options live in `reference/default-config.yaml` (also `"{exe}" default-config`). Read it before editing: every
key has a comment with its allowed values.

## Commands

Commands are the actions Valerie can perform. Keybindings, vim keys, plugin macros and agents all use them. Write a
command as its name (`toggle_sidebar`) or with options (`{{ cmd: switch_space, name: Work }}`).

Without options:
"#,
        config = config_path().display(),
    );
    for (name, title) in CATALOG {
        let _ = writeln!(g, "- `{name}`: {title}");
    }
    g.push_str("\nWith options:\n");
    for (name, args) in WITH_ARGS {
        let _ = writeln!(g, "- `{name}` `{args}`");
    }
    let _ = write!(
        g,
        r#"
Shortcut syntax (for `keybindings` and plugin `key`): modifiers `CmdOrCtrl`, `Cmd`, `Ctrl`, `Alt`, `Shift` joined with
`+`, then a key: `A`–`Z`, `0`–`9`, `F1`–`F12`, `Comma`, `Period`, `Slash`, `Equal`, `Minus`, `[`, `]`, `Up`, `Down`,
`Left`, `Right`, `Tab`, `Space`, `Enter`, `Backspace`. Example: `"CmdOrCtrl+Shift+G": {{ cmd: new_tab, url: "https://mail.google.com" }}`.

## Plugins

A plugin is a folder in `plugins/` with a `plugin.yaml`. Copy `plugins/_example/plugin.yaml`; it shows every field:

```yaml
{example}```

What each piece can do:
- **actions**: run built-in commands in order (macros).
- **js**: runs inside the current page as a function body; `return` a value to show it as a toast. It has the page's
  powers only (DOM, fetch to the page's own site).
- **run**: a shell command run in the plugin folder, any language. It gets `VALERIE_URL`, `VALERIE_TITLE` and
  `VALERIE_TAB` and can drive the browser with `valerie call` (below). Its stdout becomes a toast (`output: toast`),
  a new tab (`output: tab`) or nothing (`output: none`).
- **style.css / script.js**: injected into pages matching `matches` (hosts like `github.com` cover subdomains;
  patterns with `://` match whole URLs). CSS updates live; script.js runs after each page load.
- **on_page_load**: shell commands run when a matching page finishes loading.
- **settings**: the plugin's own options. `script.js` gets them as a `settings` object, so users (or you) can tune a
  plugin by editing its `plugin.yaml` instead of its code.

Plugins that ship with Valerie (like `youtube-speed`) are copied into `plugins/` once and then belong to the user:
edit them, disable them with `enabled: false`, or delete them.

## Controlling the browser from code

`"{exe}" call <tool> '<json arguments>'` prints the result. Use it from plugin scripts or from your own shell to look
at what the user has open (it talks to Valerie's built-in MCP server, which also works directly with MCP clients).

Tools:
"#,
        example = crate::plugins::EXAMPLE,
    );
    for t in crate::mcp::tools() {
        let _ = writeln!(g, "- `{}`: {}", t["name"].as_str().unwrap_or(""), t["description"].as_str().unwrap_or("").split(". No-option").next().unwrap_or(""));
    }
    let _ = write!(
        g,
        r#"
Examples:
```sh
"{exe}" call list_tabs '{{}}'
"{exe}" call read_page '{{"max_chars": 4000}}'
"{exe}" call run_command '{{"command": {{"cmd": "switch_space", "name": "Work"}}}}'
```

## Limits

- Passwords can't be read by agents, plugins or `valerie call`.
- Page-side `script.js` can't trigger privileged browser commands; put those in a command's `actions` or `run`.
- Data (tabs, history) lives in `{data}`; don't edit it by hand while Valerie is running.
"#,
        data = data_dir().display(),
    );
    g
}

/// Write the guide, Claude pointer, defaults reference and example plugin into the config folder.
pub fn install() {
    let dir = config_dir();
    let agents = dir.join("AGENTS.md");
    let current = std::fs::read_to_string(&agents).unwrap_or_default();
    if current.is_empty() || current.starts_with(MARKER) {
        let _ = std::fs::write(&agents, guide());
    }
    let claude = dir.join("CLAUDE.md");
    if !claude.exists() {
        let _ = std::fs::write(&claude, "@AGENTS.md\n@NOTES.md\n");
    }
    let notes = dir.join("NOTES.md");
    if !notes.exists() {
        let _ = std::fs::write(&notes, "# Notes about this Valerie setup\n\nKeep track of customisations here.\n");
    }
    let reference = dir.join("reference");
    let _ = std::fs::create_dir_all(&reference);
    let _ = std::fs::write(reference.join("default-config.yaml"), crate::config::DEFAULT_YAML);
    crate::plugins::install_bundled();
    let example = crate::plugins::plugins_dir().join("_example");
    if !example.exists() {
        let _ = std::fs::create_dir_all(&example);
        let _ = std::fs::write(example.join("plugin.yaml"), crate::plugins::EXAMPLE);
        let _ = std::fs::write(example.join("style.css"), "/* Applied to the sites in `matches` while the plugin is enabled. */\n");
    }
}
